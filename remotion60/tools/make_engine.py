#!/usr/bin/env python3
"""Generate src/engine/engine.js (ES module) from the shared painting engine in
picnic60/src + src/draw.js, and copy the art/font assets into public/."""
import os, shutil
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); ROOT = os.path.dirname(HERE)
ORDER = [('picnic60/src', 'util.js'), ('src', 'draw.js'), ('picnic60/src', 'rig.js'), ('picnic60/src', 'props.js'), ('picnic60/src', 'kit.js'),
         ('picnic60/src', 'cues.js'), ('picnic60/src', 'world.js'), ('picnic60/src', 'gl.js')]
code = '/* eslint-disable */\n// GENERATED by tools/make_engine.py — edit picnic60/src/*.js instead.\n' + '\n'.join(open(os.path.join(ROOT, d, f), encoding='utf-8').read() for d, f in ORDER)
code += '''
// ---- Remotion entry -------------------------------------------------------------
const CVX = {}; let READY = null, GLCANVAS = null;
export function initEngine(images) {
  if (READY) return READY;
  READY = (async () => {
    await loadImages(images);
    CVX.s = mkCanvas(W, H).getContext('2d'); CVX.f = mkCanvas(W, H).getContext('2d'); CVX.e = mkCanvas(W, H).getContext('2d'); CVX.ef = mkCanvas(W, H).getContext('2d');
    CVX.b = mkCanvas(480, 270).getContext('2d'); CVX.o = mkCanvas(480, 270).getContext('2d'); CVX.u = mkCanvas(W, H).getContext('2d');
    GLCANVAS = mkCanvas(W, H); GLX.init(GLCANVAS); initTextures(); buildLayers(); buildCrowd(); quiltTiles2();
  })();
  return READY;
}
// paint the world at film time t (seconds) through the camera of shot `camShot`; returns the WebGL canvas
export function renderFrame(t, frameIdx, camShot) {
  t = clamp(t, 0, DUR - 1e-4);
  const info = renderWorld(CVX.s, CVX.f, CVX.e, CVX.ef, CVX.o, t, camShot);
  CVX.b.setTransform(1, 0, 0, 1, 0, 0); CVX.b.clearRect(0, 0, 480, 270); CVX.b.filter = 'blur(5px)'; CVX.b.drawImage(CVX.e.canvas, 0, 0, 480, 270); CVX.b.drawImage(CVX.ef.canvas, 0, 0, 480, 270); CVX.b.filter = 'none';
  CVX.s.setTransform(1, 0, 0, 1, 0, 0); CVX.s.globalCompositeOperation = 'multiply'; CVX.s.globalAlpha = .14; CVX.s.drawImage(TEX.paper, 0, 0, W, H); CVX.s.globalAlpha = 1; CVX.s.globalCompositeOperation = 'source-over';
  GLX.frame({ scene: CVX.s.canvas, fg: CVX.f.canvas, emisF: CVX.ef.canvas, emis: CVX.e.canvas, bloom: CVX.b.canvas, occ: CVX.o.canvas, ui: CVX.u.canvas }, { ...info, rayAmt: (1 - clamp(info.k)) * .95, frame: frameIdx, fade: 1, uiOn: 0 });
  return GLCANVAS;
}
export { CUES, SHOTS, ACT, DUR, FPS, prog };
'''
os.makedirs(os.path.join(HERE, 'src', 'engine'), exist_ok=True)
open(os.path.join(HERE, 'src', 'engine', 'engine.js'), 'w', encoding='utf-8').write(code)
pub = os.path.join(HERE, 'public'); os.makedirs(os.path.join(pub, 'art'), exist_ok=True)
for k in ['wu_tex', 'wu_sprout', 'tex_cape', 'di_body', 'di_yawn']: shutil.copy(os.path.join(ROOT, 'assets', 'hotpot', k + '.png'), os.path.join(pub, 'art', k + '.png'))
shutil.copy(os.path.join(ROOT, 'assets', 'font', 'caption60.woff2'), os.path.join(pub, 'caption60.woff2'))
print('engine.js', os.path.getsize(os.path.join(HERE, 'src', 'engine', 'engine.js')))
